"""Worlds: elementary cellular automata (ECAs) and the priors over them.

A "world" is a program for a universal-ish machine: (rule, initial condition). Its prior
weight is 2^-(description length). Three arms:

  simplicity : rule (8 bits, the same for every rule) + an initial condition generated by a
               short seed, coded prefix-free:  1 bit constructor + EliasGamma(len) + len bits.
               This is the computable stand-in for Solomonoff/Muller's 2^-L measure.
  uniform    : same rules, but the initial condition is a uniformly random N-bit string.
               This is the "every microstate equally likely" (Boltzmann) measure.
  noise      : no rule at all; every cell of spacetime is an independent fair coin.
               The no-law baseline: what a typical fluctuation looks like.
"""
from __future__ import annotations

import math
from dataclasses import dataclass

import numpy as np


# ----------------------------------------------------------------------------- coding

def elias_gamma_len(n: int) -> int:
    """Length in bits of the Elias-gamma (prefix-free) code for a positive integer."""
    if n < 1:
        raise ValueError(n)
    return 2 * int(math.floor(math.log2(n))) + 1


# ----------------------------------------------------------------------------- ECA rules

def _rule_bits(rule: int) -> np.ndarray:
    return np.array([(rule >> i) & 1 for i in range(8)], dtype=np.uint8)


def _from_bits(bits) -> int:
    return int(sum(int(b) << i for i, b in enumerate(bits)))


def reflect(rule: int) -> int:
    b = _rule_bits(rule)
    out = np.zeros(8, np.uint8)
    for idx in range(8):
        l, c, r = (idx >> 2) & 1, (idx >> 1) & 1, idx & 1
        out[idx] = b[(r << 2) | (c << 1) | l]
    return _from_bits(out)


def complement(rule: int) -> int:
    b = _rule_bits(rule)
    out = np.zeros(8, np.uint8)
    for idx in range(8):
        out[idx] = 1 - b[7 - idx]
    return _from_bits(out)


def rule_class(rule: int) -> set[int]:
    return {rule, reflect(rule), complement(rule), reflect(complement(rule))}


def rule_representatives() -> dict[int, int]:
    """Map each minimal representative to the size of its equivalence class (88 classes)."""
    reps: dict[int, int] = {}
    for r in range(256):
        cls = rule_class(r)
        rep = min(cls)
        reps[rep] = len(cls)
    return dict(sorted(reps.items()))


def rep_of(rule: int) -> int:
    return min(rule_class(rule))


# ----------------------------------------------------------------------------- simulation

def simulate(rule: int, ic: np.ndarray, steps: int, flip: tuple[int, int] | None = None) -> np.ndarray:
    """Run an ECA. Returns spacetime array of shape (steps, N), row t = state at time t.

    flip=(t, x) flips cell x at time t before it is recorded (a single-bit perturbation).
    Neighbourhood index = 4*left + 2*centre + right (Wolfram convention).
    """
    table = _rule_bits(rule)
    N = ic.size
    out = np.empty((steps, N), np.uint8)
    x = ic.astype(np.uint8).copy()
    for t in range(steps):
        if flip is not None and flip[0] == t:
            x[flip[1]] ^= 1
        out[t] = x
        idx = (np.roll(x, 1) << 2) | (x << 1) | np.roll(x, -1)
        x = table[idx]
    return out


def translation_period(reg: np.ndarray, pmax: int) -> tuple[int, int] | None:
    """Smallest (p, s), 1 <= p <= pmax, |s| <= p, with reg[t + p] == roll(reg[t], s) for every t.

    None if there is none: the region is not a pattern that just repeats or translates with
    a short period. Covers fixed points, blinkers, shifts and the identity rule on any seed.
    """
    T, N = reg.shape
    r0 = np.ascontiguousarray(reg[0]).tobytes()
    hay = r0 + r0
    for p in range(1, min(pmax, T - 1) + 1):
        target = np.ascontiguousarray(reg[p]).tobytes()
        k = hay.find(target)
        while 0 <= k < N:
            s = (-k) % N
            if s > N // 2:
                s -= N
            if abs(s) <= p and np.array_equal(reg[p:], np.roll(reg[:-p], s, axis=1)):
                return p, s
            k = hay.find(target, k + 1)
    return None


def noise_spacetime(steps: int, N: int, rng: np.random.Generator) -> np.ndarray:
    return rng.integers(0, 2, size=(steps, N), dtype=np.uint8)


# ----------------------------------------------------------------------------- initial conditions

def build_ic(kind: str, seed_bits: str, N: int) -> np.ndarray:
    s = np.array([int(c) for c in seed_bits], dtype=np.uint8)
    if kind == "tile":
        reps = -(-N // s.size)
        return np.tile(s, reps)[:N]
    if kind == "embed":
        ic = np.zeros(N, np.uint8)
        start = (N - s.size) // 2
        ic[start:start + s.size] = s
        return ic
    raise ValueError(kind)


def ic_description_length(seed_len: int) -> int:
    """1 bit (tile/embed) + EliasGamma(len) + len seed bits."""
    return 1 + elias_gamma_len(seed_len) + seed_len


# ----------------------------------------------------------------------------- world list

@dataclass
class World:
    world_id: str
    arm: str             # simplicity | uniform | noise
    rule: int            # class representative (-1 for noise)
    multiplicity: int    # size of the rule's equivalence class
    ic_kind: str         # tile | embed | uniform | noise
    seed_bits: str       # for simplicity arm
    L_ic: float          # description length of the IC (bits); nan for uniform/noise
    weight: float        # prior weight, normalised within the arm
    rng_seed: int
    sim_rule: int = -1   # rule actually simulated, if not `rule` (complement orbit; Phase 2a)

    @property
    def run_rule(self) -> int:
        return self.rule if self.sim_rule < 0 else self.sim_rule

    def to_dict(self) -> dict:
        return dict(self.__dict__)


def make_world_list(cfg) -> list[World]:
    if getattr(cfg, "seed_mode", "crossed") == "per_rule":
        return make_world_list_2a(cfg)
    rng = np.random.default_rng(cfg.seed)
    reps = rule_representatives()
    if cfg.rules == "all":
        rule_list = list(reps.keys())
    else:
        rule_list = sorted({rep_of(int(r)) for r in cfg.rules})

    # Simplicity-prior initial conditions, shared across rules (variance reduction).
    ic_set = []  # (kind, bits, L, importance)
    for ell in range(1, cfg.ic_max_len + 1):
        n_all = 2 ** ell
        if ell <= cfg.ic_exact_len or n_all <= cfg.ic_per_len:
            seeds, m = range(n_all), n_all
        else:
            m = cfg.ic_per_len
            seeds = rng.choice(n_all, size=m, replace=False)
        for kind in ("tile", "embed"):
            for sv in seeds:
                bits = format(int(sv), f"0{ell}b")
                ic_set.append((kind, bits, ic_description_length(ell), n_all / m))

    # Different programs can produce the same world (tile "0" == tile "00" == embed "0").
    # The prior of a world is the SUM over every program that produces it (Solomonoff), so
    # merge duplicates, keeping the shortest program as the label.
    worlds: list[World] = []
    raw: dict = {}
    for r in rule_list:
        for kind, bits, L, imp in ic_set:
            ic_key = build_ic(kind, bits, cfg.N).tobytes()
            w = (reps[r] / 256.0) * (2.0 ** -L) * imp
            if (r, ic_key) in raw:
                ent = raw[(r, ic_key)]
                ent[4] += w
                if L < ent[3]:
                    ent[1], ent[2], ent[3] = kind, bits, L
            else:
                raw[(r, ic_key)] = [r, kind, bits, L, w]
    Z = sum(x[4] for x in raw.values())
    for r, kind, bits, L, w in raw.values():
        worlds.append(World(f"simp-r{r}-{kind}-{bits}", "simplicity", r, reps[r], kind, bits,
                            float(L), w / Z, int(rng.integers(2**31))))
    # uniform arm
    Zu = sum(reps[r] for r in rule_list) * cfg.n_uniform
    for r in rule_list:
        for i in range(cfg.n_uniform):
            worlds.append(World(f"unif-r{r}-{i}", "uniform", r, reps[r], "uniform", "",
                                float("nan"), reps[r] / Zu, int(rng.integers(2**31))))
    # noise arm
    for i in range(cfg.n_noise):
        worlds.append(World(f"noise-{i}", "noise", -1, 1, "noise", "", float("nan"),
                            1.0 / cfg.n_noise, int(rng.integers(2**31))))
    return worlds


def ring_size(world, cfg) -> int:
    """Cells in the world's ring. With cfg.seam_free (README 3b.8 A9) a tile world with seed
    length d runs on d * floor(N / d) cells, so the tiling closes without a defect at the
    wrap-around. That is a multiple of d and therefore of the tile's primitive period."""
    if getattr(cfg, "seam_free", False) and world.ic_kind == "tile":
        d = len(world.seed_bits)
        return d * (cfg.N // d)
    return cfg.N


def realise(world: World, cfg) -> tuple[np.ndarray, np.ndarray, tuple[int, int]]:
    """Return (spacetime, perturbed spacetime, flip location)."""
    rng = np.random.default_rng(world.rng_seed)
    steps = cfg.T0 + cfg.T + cfg.hf + 1
    t_flip = cfg.T0 + cfg.T // 2
    n_ring = ring_size(world, cfg)
    x_flip = int(rng.integers(cfg.N)) % n_ring   # drawn at the nominal N, as before
    if world.arm == "noise":
        st = noise_spacetime(steps, cfg.N, rng)
        pert = st.copy()
        pert[t_flip, x_flip] ^= 1  # noise has no dynamics, so the flip stays a single cell
        return st, pert, (t_flip, x_flip)
    if world.arm == "uniform":
        ic = rng.integers(0, 2, size=cfg.N, dtype=np.uint8)
    else:
        ic = build_ic(world.ic_kind, world.seed_bits, n_ring)
    st = simulate(world.run_rule, ic, steps)
    pert = simulate(world.run_rule, ic, steps, flip=(t_flip, x_flip))
    return st, pert, (t_flip, x_flip)


# ----------------------------------------------------------------------------- Phase 2a world list

def reflection_orbit(rule: int) -> set[int]:
    return {rule, reflect(rule)}


def phase1_program_keys(dirs) -> set:
    """(rule, ic_kind, seed_bits) of every simplicity-arm world in earlier result directories."""
    import json
    import os
    keys = set()
    for d in dirs:
        path = os.path.join(d, "results.jsonl")
        if not os.path.exists(path):
            raise SystemExit(f"exclude_programs_from: {path} not found (needed to keep the run disjoint)")
        with open(path) as f:
            for line in f:
                if line.strip():
                    w = json.loads(line)["world"]
                    if w["arm"] == "simplicity":
                        keys.add((w["rule"], w["ic_kind"], w["seed_bits"]))
    return keys


def make_world_list_2a(cfg, return_info: bool = False):
    """Phase 2a confirmation design (README 3b.6).

    Differences from make_world_list:
      * long seeds are sampled independently for each rule (seed clusters nest within rules)
        and oversampled (cfg.ic_per_len_long per length);
      * sampled seeds never repeat a simplicity-arm program from cfg.exclude_programs_from;
        the excluded share of each (rule, length) is returned for the report. The sampled
        seeds stand in for every seed of their length (importance weight 2^len / m);
      * complement approximation removed: a class is the union of the reflection orbit of
        its representative r and that of complement(r). Tile seeds are exact under the
        class weight (the complement of a tiled seed is a tiled seed of the same length), so
        they are run once under r. Embed seeds are run under r with weight |orbit(r)|/256
        and, when complement(r) is in a different orbit, also under that orbit's smallest
        rule with weight |orbit(comp r)|/256.
    Every world keeps `rule` = class representative, so rule clusters and rule priors work
    unchanged; `sim_rule` is the rule actually simulated.
    """
    reps = rule_representatives()
    rule_list = list(reps) if cfg.rules == "all" else sorted({rep_of(int(r)) for r in cfg.rules})
    excluded = phase1_program_keys(cfg.exclude_programs_from) if cfg.exclude_programs_from else set()
    m_long = cfg.ic_per_len_long or cfg.ic_per_len
    excl_info = {}   # (rule, len) -> share of seeds excluded
    raw: dict = {}
    for r in rule_list:
        rr = np.random.default_rng([cfg.seed, r])
        orb = reflection_orbit(r)
        comp = complement(r)
        comp_rule = -1 if comp in orb else min(reflection_orbit(comp))
        w_tile = reps[r] / 256.0
        w_embed = len(orb) / 256.0
        w_comp = (reps[r] - len(orb)) / 256.0
        for ell in range(1, cfg.ic_max_len + 1):
            n_all = 2 ** ell
            if ell <= cfg.ic_exact_len:
                seeds, imp = list(range(n_all)), 1.0
            else:
                pool = [sv for sv in range(n_all)
                        if not any((r, k, format(sv, f"0{ell}b")) in excluded for k in ("tile", "embed"))]
                excl_info[(r, ell)] = 1.0 - len(pool) / n_all
                m = min(m_long if ell >= cfg.ic_long_from else cfg.ic_per_len, len(pool))
                seeds = [int(x) for x in rr.choice(pool, size=m, replace=False)] if m else []
                imp = n_all / m if m else 0.0
            L = ic_description_length(ell)
            for sv in seeds:
                bits = format(sv, f"0{ell}b")
                progs = [("tile", r, -1, w_tile), ("embed", r, -1, w_embed)]
                if comp_rule >= 0:
                    progs.append(("embed", r, comp_rule, w_comp))
                for kind, rep, sim, wr in progs:
                    key = (rep, sim, build_ic(kind, bits, cfg.N).tobytes())
                    w = wr * (2.0 ** -L) * imp
                    if key in raw:
                        ent = raw[key]
                        ent["w"] += w
                        if L < ent["L"]:
                            ent.update(kind=kind, bits=bits, L=L)
                    else:
                        raw[key] = dict(rule=rep, sim=sim, kind=kind, bits=bits, L=L, w=w)
    rng = np.random.default_rng([cfg.seed, 9999])
    Z = sum(e["w"] for e in raw.values())
    worlds: list[World] = []
    for e in raw.values():
        tag = f"r{e['rule']}" + (f"c{e['sim']}" if e["sim"] >= 0 else "")
        worlds.append(World(f"simp-{tag}-{e['kind']}-{e['bits']}", "simplicity", e["rule"], reps[e["rule"]],
                            e["kind"], e["bits"], float(e["L"]), e["w"] / Z, int(rng.integers(2**31)),
                            sim_rule=e["sim"]))
    Zu = sum(reps[r] for r in rule_list) * cfg.n_uniform
    for r in rule_list:
        for i in range(cfg.n_uniform):
            worlds.append(World(f"unif-r{r}-{i}", "uniform", r, reps[r], "uniform", "", float("nan"),
                                reps[r] / Zu, int(rng.integers(2**31))))
    for i in range(cfg.n_noise):
        worlds.append(World(f"noise-{i}", "noise", -1, 1, "noise", "", float("nan"),
                            1.0 / cfg.n_noise, int(rng.integers(2**31))))
    if return_info:
        return worlds, excl_info
    return worlds
